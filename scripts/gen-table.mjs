// Builds src/levels-table.js: for every level, the generator attempt that yields a verified-solvable board
// near its target difficulty, plus the optimal solution length (par). Runs 10 worker processes in parallel.
import { spawn } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { TOTAL_LEVELS } from '../src/game.js'

const SPAN = 20
const jobs = []
for (let from = 1; from <= TOTAL_LEVELS; from += SPAN) {
  const to = Math.min(TOTAL_LEVELS, from + SPAN - 1)
  jobs.push(
    new Promise((resolve, reject) => {
      const p = spawn('node', [new URL('./gen-part.mjs', import.meta.url).pathname, String(from), String(to)], { stdio: 'inherit' })
      p.on('exit', (code) => (code === 0 ? resolve(from) : reject(new Error(`worker ${from} failed`))))
    }),
  )
}
await Promise.all(jobs)
const rows = []
for (let from = 1; from <= TOTAL_LEVELS; from += SPAN) rows.push(...JSON.parse(readFileSync(`/tmp/blocked-in-part-${from}.json`, 'utf8')))
writeFileSync(new URL('../src/levels-table.js', import.meta.url), `// Generated by scripts/gen-table.mjs - [generator attempt, optimal solution length] per level.\nexport default ${JSON.stringify(rows)}\n`)
console.log('wrote', rows.length, 'pars', rows.map((r) => r[1]).join(','))
