// Finds, for every level, the generator attempt that yields a verified-solvable board near its target
// difficulty, and records the optimal solution length (par).
import { writeFileSync } from 'node:fs'
import { searchLevel, TOTAL_LEVELS } from '../src/game.js'

const rows = []
const t0 = Date.now()
for (let n = 1; n <= TOTAL_LEVELS; n++) {
  const found = searchLevel(n, 500, 80000)
  if (!found) throw new Error(`no solvable board for level ${n}`)
  rows.push(found)
  if (n % 20 === 0) console.log(n, found, `${Math.round((Date.now() - t0) / 1000)}s`)
}
writeFileSync(new URL('../src/levels-table.js', import.meta.url), `// Generated by scripts/gen-table.mjs - [generator attempt, optimal solution length] per level.\nexport default ${JSON.stringify(rows)}\n`)
console.log('wrote', rows.length, 'pars', rows.map((r) => r[1]).join(','))
